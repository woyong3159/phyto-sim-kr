const problems = [];
for (const [id, rows] of Object.entries(RAW)) {
  for (const [k, v] of Object.entries(rows)) {
    if (v.length !== 13) problems.push(`${id}.${k}: 값 개수 ${v.length}`);
    const m = v.slice(0, 12);
    const year = v[12];
    if (k === 'PRCP' || k === 'PDAY' || k === 'SUN') {
      const sum = m.reduce((a, b) => a + b, 0);
      const tol = k === 'PDAY' ? 0.6 : Math.max(1.0, year * 0.001);
      if (Math.abs(sum - year) > tol) problems.push(`${id}.${k}: 합 ${sum.toFixed(1)} ≠ 연값 ${year}`);
    } else {
      const mean = m.reduce((a, b, i) => a + b * DAYS[i], 0) / 365;
      if (Math.abs(mean - year) > 0.25) problems.push(`${id}.${k}: 평균 ${mean.toFixed(2)} ≠ 연값 ${year}`);
    }
  }
  for (let i = 0; i < 12; i++) {
    if (!(rows.TMIN[i] < rows.TAVG[i] && rows.TAVG[i] < rows.TMAX[i])) problems.push(`${id}: ${i + 1}월 최저<평균<최고 위반`);
  }
}
